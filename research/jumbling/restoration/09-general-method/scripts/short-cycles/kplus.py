"""Exact combinatorial action of the rotation group K+ on the caps, pieces and sticker slots of the retained model.
- caps: K+ is generated by the cap permutations `rotperms` (one per primitive); a breadth-first search from six of
  them gives its 7,200 elements (`group`);
- pieces: a piece is determined by its cap signature (mask), and sigma maps the piece with mask M to the piece with
  mask sigma(M) (`piece_map`, with Zobrist hashes of the masks and an exact membership check);
- slots: a slot is determined by (piece, facet), and sigma maps (q, f) to (sigma q, sigma f) (`slot_map`). The facet
  of a slot is the cap whose normal is nearest to the slot centre. That is a floating-point reading, so `check`
  verifies its consequence exactly: for each of the 1,200 primitives p with rotation r, P_p(s) = r(s) for every slot
  s that p moves, so each primitive acts on its cap region as its rotation.
Run from the repository root: python3 -I -B kplus.py (about two minutes; prints the order of K+ and the number of
mismatches, which must be 0). Research only: exact synthetic geometry; no Windows, DirectX, input or performance claim.
"""
import numpy as np

m = np.load('assets/model.npz')
pz = np.load('assets/primitives.npz')
SRC, DST, OFF = pz['src'], pz['dst'], pz['offsets']
mo, mv = m['mask_offsets'].astype(np.int64), m['mask_values'].astype(np.int64)
fo, fv = m['face_offsets'].astype(np.int64), m['face_values'].astype(np.int64)
sp = m['slot_piece'].astype(np.int64)
rot = m['rotperms'].astype(np.int64)
NP, NS = len(mo) - 1, len(sp)
Z = np.random.default_rng(12345).integers(0, 2**63, 600, dtype=np.int64).astype(np.uint64)
H0 = np.add.reduceat(Z[mv], mo[:-1])
assert len(np.unique(H0)) == NP, 'mask hashes collide'
order = np.argsort(H0)
Hs = H0[order]


def piece_map(sig):
    """sig[c] is the image of cap c. Returns pmap with pmap[q] the image of piece q."""
    h = np.add.reduceat(Z[sig[mv]], mo[:-1])
    i = np.minimum(np.searchsorted(Hs, h), NP - 1)
    assert np.all(Hs[i] == h), 'a mask image is not a piece'
    pmap = order[i]
    # the hash only selects a candidate; check that the image mask is exactly the candidate's mask
    for q in range(0, NP, 4999):
        r = pmap[q]
        assert sorted(sig[mv[mo[q]:mo[q + 1]]].tolist()) == sorted(mv[mo[r]:mo[r + 1]].tolist())
    return pmap


normals, cen = m['normals'], m['slot_centers']
facet = np.argmax(cen @ normals.T, axis=1).astype(np.int64)
key = sp * 600 + facet
assert len(np.unique(key)) == NS, 'a slot is not determined by (piece, facet)'
for q in range(0, NP, 997):
    assert sorted(facet[sp == q].tolist()) == sorted(fv[fo[q]:fo[q + 1]].tolist())
korder = np.argsort(key)
ks = key[korder]


def slot_map(sig, pmap=None):
    """Returns smap with smap[s] the image of slot s under sig."""
    pmap = piece_map(sig) if pmap is None else pmap
    k2 = pmap[sp] * 600 + sig[facet]
    i = np.minimum(np.searchsorted(ks, k2), NS - 1)
    assert np.all(ks[i] == k2), 'a slot image is missing'
    return korder[i]


def group():
    """The 7,200 cap permutations of K+, the identity first."""
    ident = np.arange(600, dtype=np.int64)
    seen = {ident.tobytes(): ident}
    frontier = [ident]
    gens = [rot[0], rot[1], rot[2], rot[3], rot[26], rot[27]]
    while frontier:
        nxt = []
        for x in frontier:
            for g in gens:
                y = g[x]  # first x, then g
                k = y.tobytes()
                if k not in seen:
                    seen[k] = y
                    nxt.append(y)
        frontier = nxt
    return list(seen.values())


def prim_perm(a):
    """The slot permutation of primitive a (1..1200): P[s] is the slot the sticker at s moves to."""
    P = np.arange(NS, dtype=np.int64)
    P[SRC[OFF[a - 1]:OFF[a]]] = DST[OFF[a - 1]:OFF[a]]
    return P


def check():
    bad = 0
    for a in range(1, 1201):
        s, d = SRC[OFF[a - 1]:OFF[a]], DST[OFF[a - 1]:OFF[a]]
        bad += int(np.sum(slot_map(rot[a - 1])[s] != d))
    return bad


if __name__ == '__main__':
    import json
    K = group()
    print(json.dumps({'K_plus_order': len(K), 'primitive_equivariance_mismatches': check()}))
