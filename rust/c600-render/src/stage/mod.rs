//! User shader stages for the device (C9 U5a; RPI.68 to RPI.78), under the interface contract `m600-stage-hlsl/1`
//! (draft of 19 Nov 2026, shared with the core's ABI 6). A stage reaches this module only as a
//! [`c600_check::CheckedStage`], the form in which LP2's stage checker admitted it under the host's limits (RPI.68),
//! never as a callable or as shader text from a program. From it this module makes:
//!
//! - [`bind`]: the adapter's parameter binding (`binding/1`, draft): the entry's parameters by name to the host's
//!   inputs, and the declared arrays, in declaration order, to one structured buffer;
//! - [`generate`]: deterministic HLSL text: the same checked stage and [`GENERATOR_VERSION`] give the same bytes
//!   (RPI.78);
//! - [`evaluate`]: the stage's CPU reference (RPI.74): the same checked definition in binary32, in the same order and
//!   under the same coverage rule as the text;
//! - [`parse_limits`] and [`record`]: the host's limits file and the JSON record that the bin `c600-stage-hlsl`
//!   writes beside the text.
//!
//! Not here: compiling the text with DXC and its compile record (U5b), the raster bound, frame stop and predication
//! on a device (RPI.72), and quarantine (c600-display's `Quarantine`, LP3's host). Agreement between [`evaluate`] and
//! a device is recorded, never a proof (RPI.35).
//!
//! Draft readings of the contract (each also at its place):
//!
//! - `Unit` has no HLSL value: a `Unit` local, parameter, result or record field, and a record whose fields are all
//!   such, is left out of the text; its expression still runs for coverage, and a function of such a result is
//!   `void`.
//! - Only the functions the entry reaches are emitted, callees before callers, so the text needs no prototype. Names
//!   keep the contract's numbering: `m600_f<module index>_<function index>` in the checked definition.
//! - Each record type (fields compared by name) is one struct, numbered by first occurrence in emission order, with
//!   the fields in the order of that occurrence; a field `f` is the member `m_f`. A struct of nested records follows
//!   the structs of its fields. A record value is a local whose members are assigned in struct order.
//! - Parameters are `m600_a<i>` (`i` the IR position), locals `m600_v<n>`, loop counters `m600_i<k>`. A loop bound is
//!   written `Nu`, a count of 0 emits no loop, and `index(a, i)` is one literal position `[offset + i]u`.
//! - The fixed entry checks the inputs the entry takes and every element of the declared arrays; an input the stage
//!   omits is not checked.
//! - `approx_and` evaluates both operands, as the interpreter does.
//! - The record also names the contract and the stage module.

