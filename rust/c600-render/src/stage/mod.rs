/// The interface contract the generated text follows.
pub const CONTRACT: &str = "m600-stage-hlsl/1";
/// The generator's version. A change to the generated bytes for the same checked stage changes it (RPI.78).
pub const GENERATOR_VERSION: &str = "c600-render-stage-hlsl/1";
/// The adapter's parameter binding (draft).
pub const BINDING_VERSION: &str = "binding/1";

/// A type a checked stage holds: the stage checker's types without the array inputs, record fields in written order.
#[derive(Clone, Debug, PartialEq, Eq)]
pub(crate) enum T {
    F32,
    Bool,
    Unit,
    Rec(Vec<(String, T)>),
}

impl T {
    /// The type of a parameter or result; `None` for an array input or a type no stage holds.
    pub(crate) fn of(q: &QTy) -> Option<T> {
        match &q.ty {
            Ty::Approx(24) => Some(T::F32),
            Ty::ApproxBool => Some(T::Bool),
            Ty::Unit => Some(T::Unit),
            Ty::Record(fields) => {
                fields.iter().map(|(n, f)| T::of(f).map(|t| (n.clone(), t))).collect::<Option<Vec<_>>>().map(T::Rec)
            }
            _ => None,
        }
    }

    /// Whether a value of the type carries nothing in the text (draft): `Unit`, or a record of such fields only.
    pub(crate) fn erased(&self) -> bool {
        match self {
            T::Unit => true,
            T::Rec(fields) => fields.iter().all(|(_, t)| t.erased()),
            _ => false,
        }
    }

    /// The type compared by field names: fields sorted, at every depth.
    pub(crate) fn key(&self) -> T {
        match self {
            T::Rec(fields) => {
                let mut out: Vec<(String, T)> = fields.iter().map(|(n, t)| (n.clone(), t.key())).collect();
                out.sort_by(|a, b| a.0.cmp(&b.0));
                T::Rec(out)
            }
            other => other.clone(),
        }
    }

    pub(crate) fn field(&self, name: &str) -> Option<&T> {
        match self {
            T::Rec(fields) => fields.iter().find(|(n, _)| n == name).map(|(_, t)| t),
            _ => None,
        }
    }
}

/// Whether a parameter is an array input: `List<Approx<24>>`.
pub(crate) fn is_array(q: &QTy) -> bool {
    matches!(&q.ty, Ty::List(e) if e.ty == Ty::Approx(24))
}

/// The binary32 value of a stage literal. The stage checker admitted only decimals that denote an exact finite
/// binary32 value, so Rust's correctly rounded parse gives that value.
pub(crate) fn literal(e: &Expr) -> Option<f32> {
    match e {
        Expr::Lit(Lit::Approx { decimal, precision: 24 }) => decimal.parse::<f32>().ok().filter(|v| v.is_finite()),
        _ => None,
    }
}

/// A literal natural: a loop count or an index position.
pub(crate) fn nat(e: &Expr) -> Option<u64> {
    match e {
        Expr::Lit(Lit::Nat(n)) => n.parse().ok(),
        _ => None,
    }
}

/// The function a call names, as (module, function) indices in the checked definition.
pub(crate) fn callee(defs: &[Module], mi: usize, callee: &Callee) -> Option<(usize, usize)> {
    let Callee::Fn { module, name } = callee else { return None };
    let mj = match module {
        None => mi,
        Some(m) => defs.iter().position(|d| &d.name == m)?,
    };
    let fj = defs[mj].functions.iter().position(|f| &f.name == name)?;
    Some((mj, fj))
}

/// The functions `entry` reaches, itself included, callees before callers: a depth-first walk of the calls in
/// evaluation order (operands before the call, a `display_if` condition before its branches). A callee that does not
/// resolve is left out; the generator refuses its call.
pub(crate) fn reached(defs: &[Module], entry: (usize, usize)) -> Vec<(usize, usize)> {
    fn calls(defs: &[Module], mi: usize, e: &Expr, out: &mut Vec<(usize, usize)>) {
        for child in e.children() {
            calls(defs, mi, child, out);
        }
        if let Expr::Call { callee: c, .. } = e {
            out.extend(callee(defs, mi, c));
        }
    }
    fn visit(defs: &[Module], f: (usize, usize), seen: &mut Vec<(usize, usize)>, out: &mut Vec<(usize, usize)>) {
        if seen.contains(&f) {
            return;
        }
        seen.push(f);
        let mut found = Vec::new();
        calls(defs, f.0, &defs[f.0].functions[f.1].body, &mut found);
        for c in found {
            visit(defs, c, seen, out);
        }
        out.push(f);
    }
    let mut out = Vec::new();
    visit(defs, entry, &mut Vec::new(), &mut out);
    out
}

/// The JSON record of a generated stage that the bin writes beside the text: the kind, the digest, the module and
/// entry, the declared ops, overdraw and arrays, the binding, the contract and generator versions and the SHA-256 of
/// the text's bytes. Canonical JSON (sorted keys, no spaces) and a final newline, so the same stage gives the same
/// bytes.
pub fn record(stage: &CheckedStage, generated: &Generated) -> String {
    let decl = stage.declaration();
    let int = |n: u64| i64::try_from(n).map(Value::Int).unwrap_or_else(|_| Value::Number(n.to_string()));
    let arrays = generated
        .binding
        .arrays
        .iter()
        .map(|a| {
            object([("name", Value::String(a.name.clone())), ("offset", int(a.offset)), ("length", int(a.length))])
        })
        .collect();
    let params = generated
        .binding
        .params
        .iter()
        .map(|p| {
            let mut fields = BTreeMap::from([("name".to_string(), Value::String(p.name.clone()))]);
            match &p.bound {
                Bound::Input(input) => fields.insert("input".into(), Value::String(input.name().into())),
                Bound::Array(k) => {
                    fields.insert("array".into(), Value::String(generated.binding.arrays[*k].name.clone()))
                }
            };
            Value::Object(fields)
        })
        .collect();
    let binding = object([
        ("version", Value::String(BINDING_VERSION.into())),
        ("buffer", Value::String(generated.binding.buffer().into())),
        ("register", Value::String(generated.binding.register().into())),
        ("params", Value::Array(params)),
    ]);
    let record = object([
        ("contract", Value::String(CONTRACT.into())),
        ("generator", Value::String(GENERATOR_VERSION.into())),
        ("kind", Value::String(stage.kind().name().into())),
        ("digest", Value::String(generated.digest.clone())),
        ("module", Value::String(stage.module().into())),
        ("entry", Value::String(stage.entry().into())),
        ("ops", int(decl.ops)),
        ("overdraw", int(decl.overdraw)),
        ("arrays", Value::Array(arrays)),
        ("binding", binding),
        ("hlsl_sha256", Value::String(c600_digest::sha256_hex(generated.hlsl.as_bytes()))),
    ]);
    format!("{}\n", record.canonical())
}
